export type TranslationKey = typeof translations.id;

export function useTranslation() {
  const language = usePosStore((state) => state.language) || "id";
  const setLanguage = usePosStore((state) => state.setLanguage);

  const t = (translations[language] || translations.id) as TranslationKey;

  const toggleLanguage = () => {
    setLanguage(language === "id" ? "en" : "id");
  };

  return {
    lang: language,
    language,
    isIndonesian: language === "id",
    isEnglish: language === "en",
    setLanguage,
    toggleLanguage,
    t,
  };
}
